/// Спецификация зон касания (хитбоксов) объектов игры «Планетарная защита».
///
/// Все значения — по спецификации хитбоксов (issue #18, `docs/hitboxes.md`,
/// раздел 1 «Таблица расчёта хитбоксов объектов»). Конфигурация лежит в
/// [hitboxSpecs] и нигде больше: код игры читает размеры зон касания только
/// отсюда.
library;

import '../pacing/threat_type.dart';

/// Зона касания одного типа объекта.
///
/// Хитбоксы проектируются шире видимых спрайтов (запас прощения,
/// forgiveness), чтобы мелкие и быстрые цели можно было отбивать боковым
/// зрением, не закрывая их пальцем.
class HitboxSpec {
  const HitboxSpec({
    required this.visualMinPt,
    required this.visualMaxPt,
    required this.touchZonePt,
    required this.physicalSizeMm,
    required this.forgivenessNote,
    this.strikeZonePt,
    this.twoFingerZonePt,
  });

  /// Минимальный визуальный диаметр спрайта, pt.
  final double visualMinPt;

  /// Максимальный визуальный диаметр спрайта, pt.
  final double visualMaxPt;

  /// Диаметр основной зоны касания (хитбокса), pt.
  ///
  /// Для спасательной капсулы это широкая зона ведения; для тяжёлого
  /// болида — зона отбивания одним пальцем.
  final double touchZonePt;

  /// Физический размер зоны касания, мм (привязка к подушечке пальца
  /// взрослого человека 8–11 мм).
  final double physicalSizeMm;

  /// UX-логика и запас прощения (forgiveness) из таблицы спецификации.
  final String forgivenessNote;

  /// Диаметр узкой центральной зоны резкого удара, pt.
  ///
  /// Задан только для спасательной капсулы (асимметричный хитбокс):
  /// резкий удар принимается лишь в центральной зоне, чтобы игрок случайно
  /// не разбил капсулу, отбивая астероид рядом с ней. `null` — зона удара
  /// совпадает с основной зоной касания.
  final double? strikeZonePt;

  /// Максимальный диаметр зоны силового толчка двумя пальцами, pt.
  ///
  /// Задан только для тяжёлого болида: между пальцами по обе стороны от
  /// объекта натягивается силовая дуга. `null` — двухпальцевый жест для
  /// объекта не предусмотрен.
  final double? twoFingerZonePt;

  /// Запас прощения относительно максимального визуального диаметра.
  double get forgivenessRatio => touchZonePt / visualMaxPt;

  /// Радиус основной зоны касания, pt.
  double get touchRadiusPt => touchZonePt / 2;
}

