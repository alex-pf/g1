/// Типы объектов (угроз и спасательных капсул) игры «Планетарная защита».
///
/// Номенклатура и урон согласованы со спецификацией баланса объектов
/// (issue #7, `docs/balance.md`): типы и значения урона ниже дублируют
/// колонку «Урон / эффект для планет» её таблицы взаимодействий.
library;

/// Тип игрового объекта, появляющегося в космосе во время раунда.
enum ThreatType {
  /// Обычный астероид: −1 звезда при попадании в планету.
  asteroid(starDamage: 1.0, isHostile: true),

  /// Хрупкий гигант: −1 звезда при попадании целиком; раскалывается
  /// на 3–4 осколка от резкого удара.
  giant(starDamage: 1.0, isHostile: true),

  /// Осколок гиганта: −1/4 звезды.
  giantFragment(starDamage: 0.25, isHostile: true),

  /// Спасательная капсула: не угроза, а цель сопровождения;
  /// +1/4 звезды при мягкой посадке на Землю (US-05, issue #9).
  escapeCapsule(starDamage: -0.25, isHostile: false),

  /// Маневрирующий зонд: −1 звезда; после отбивания снова наводится
  /// на планету (US-06, issue #10).
  probe(starDamage: 1.0, isHostile: true),

  /// Тяжёлый болид: −1,5 звезды; высокая инерция (US-09, issue #13).
  heavyBolide(starDamage: 1.5, isHostile: true);

  const ThreatType({required this.starDamage, required this.isHostile});

  /// Изменение шкалы жизни планеты (в звёздах) при достижении объектом
  /// планеты. Отрицательное значение — восстановление (капсула).
  final double starDamage;

  /// Враждебен ли объект планете (капсула — нет).
  final bool isHostile;
}
