/// Таблица урона/лечения объектов в четвертях звезды (шаг шкалы — 1/4).
///
/// Значения согласованы со спецификацией баланса (issue #7) и
/// UX-требованиями индикатора жизней (issue #15,
/// docs/ux-health-indicator.md). При изменении баланса правится только
/// этот enum — модель и UI от конкретных чисел не зависят.
library;

enum ImpactKind {
  /// Осколок: −1/4 звезды.
  fragment(-1, 'Осколок'),

  /// Астероид: −1 звезда.
  asteroid(-4, 'Астероид'),

  /// Маневрирующий зонд: −1,5 звезды.
  probe(-6, 'Зонд'),

  /// Сверхтяжёлый металлический болид: −1,5 звезды.
  bolid(-6, 'Болид'),

  /// Спасательная капсула: +1/4 звезды.
  capsule(1, 'Капсула');

  const ImpactKind(this.quartersDelta, this.label);

  /// Изменение шкалы в четвертях звезды (отрицательное — урон).
  final int quartersDelta;

  /// Человекочитаемое название для отладочного UI.
  final String label;

  bool get isHeal => quartersDelta > 0;
  bool get isDamage => quartersDelta < 0;
}
